"""The lifter's vector FMIN / FMAX / FMINNM / FMAXNM (.2S / .4S) on SSE (A64_VFMINMAX, a64_vfminmax32), game-free:
bit-exact with the per-lane exact blocks they sit in front of.

Guest words (hand-encoded, with aliased registers too) go through a64emit.translate and a64_lift.op_text twice: with
A64_VFMINMAX=1 (the SSE test, the exact block behind it) and =0 (the exact block alone). tests/vfminmax_test.c runs both
on random registers (zeros of both signs, equal operands, subnormals, infinities, quiet and signalling NaNs) under random
FPCR (FZ, DN, other control bits) and FPSR states, and compares the whole Ctx. Built at -march=x86-64-v3 and
-march=x86-64-v2, with the build's FP flags, the headers made as tests/test_vfpx_elem.py makes them.

    python -I -B tests/test_vfminmax.py [--cc clang] [--cxx clang++]

~5 s here. It has teeth (each by hand, then restored): FMIN's signed-zero fix dropped (`_mm_and_si128(zeros, a)` ->
zero): 114707 mismatches at v2; the FZ subnormal test dropped: 82998.

Skipped (exit 0) on a host that is not x86-64, without a C/C++ compiler, or on a CPU without x86-64-v2.
"""
import argparse
import os
import platform
import shutil
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import test_fpx_sticky as sticky  # noqa: E402  (its compiler search, flags and header generation)

CASES, SEED = 3000000, 20261114
GUEST = (("FMIN v0.4s, v1.4s, v2.4s", 0x4EA2F420), ("FMAX v0.4s, v1.4s, v2.4s", 0x4E22F420),
         ("FMINNM v0.4s, v1.4s, v2.4s", 0x4EA2C420), ("FMAXNM v0.4s, v1.4s, v2.4s", 0x4E22C420),
         ("FMIN v0.2s, v1.2s, v2.2s", 0x0EA2F420), ("FMAXNM v0.2s, v1.2s, v2.2s", 0x0E22C420),
         ("FMIN v1.4s, v1.4s, v1.4s", 0x4EA1F421), ("FMAX v2.4s, v1.4s, v2.4s", 0x4E22F422))


def cases(a64emit, a64_lift, used):
    words = [(0x1000, w) for _, w in GUEST]
    lifted, fl = a64emit.translate(words)
    if any(fl):
        raise SystemExit("vfminmax: a64emit did not translate the guest words: %s" % fl)
    os.environ["A64_VFMINMAX"] = "0"
    old = [a64_lift.op_text(t, used) for t in lifted]
    os.environ["A64_VFMINMAX"] = "1"
    try:
        new = [a64_lift.op_text(t, used) for t in lifted]
    finally:
        os.environ["A64_VFMINMAX"] = "0"
    out = ["/* Generated by tests/test_vfminmax.py */"]
    for i, (n, o) in enumerate(zip(new, old)):
        if "a64_vfminmax32(" not in n or "a64_vfminmax32(" in o or "_less=" not in o:
            raise SystemExit("vfminmax: %s was not vectorized (or the old form is not the exact block):\n%s\n%s" % (GUEST[i][0], n, o))
        out.append("static void g_new%d(Ctx *__restrict c) { %s }" % (i, n))
        out.append("static void g_old%d(Ctx *__restrict c) { %s }" % (i, o))
        out.append("static void g_newh%d(Ctx *__restrict c) { %s }" % (i, a64_lift.hot_text(n)))
        out.append("static void g_oldh%d(Ctx *__restrict c) { %s }" % (i, a64_lift.hot_text(o)))
    out.append("static const struct { const char *name; void (*n)(Ctx *), (*o)(Ctx *), (*nh)(Ctx *), (*oh)(Ctx *); } GUEST[] = {%s};"
               % ", ".join('{"%s", g_new%d, g_old%d, g_newh%d, g_oldh%d}' % (g[0], i, i, i, i) for i, g in enumerate(GUEST)))
    return "\n".join(out) + "\n"


def generate(cxx, tmp, flags):
    dll = os.path.join(tmp, "a64emit.dll" if os.name == "nt" else "liba64emit.so")
    sticky.build([cxx, "-std=c++20", "-O0", "-shared", "-Wno-everything", "-o", dll, os.path.join(sticky.KIT, "lift", "a64emit.cpp")]
                 + flags + ([] if os.name == "nt" else ["-fPIC"]), "a64emit")
    import build_emit
    build_emit.build = lambda force=False: dll
    import a64_lift
    import a64_rtgen
    import a64emit
    used = set()
    try:
        a64_rtgen.write(tmp)
        text = cases(a64emit, a64_lift, used)
    finally:
        if a64emit._lib is not None:
            import _ctypes
            (_ctypes.FreeLibrary if os.name == "nt" else _ctypes.dlclose)(a64emit._lib._handle)
            a64emit._lib = None
    with open(os.path.join(tmp, "vfminmax_cases.h"), "w", newline="\n") as f:
        f.write(text)
    with open(os.path.join(tmp, "a64_fpx.h"), "w", newline="\n") as f:
        os.environ["A64_VFMINMAX"] = "1"   # (the header with the helper, as a lift with the switch writes it)
        try:
            f.write(a64_lift.fpx_header(used))
        finally:
            os.environ["A64_VFMINMAX"] = "0"


def main():
    # (the switches this test does not cover stay off)
    os.environ["A64_FPX_SLOWPATH"] = "0"
    os.environ["A64_FPX_FMA3"] = "0"
    os.environ["A64_VFPX_ELEM"] = "0"
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cc")
    p.add_argument("--cxx")
    a = p.parse_args()
    if platform.machine().lower() not in ("x86_64", "amd64"):
        print("vfminmax: skipped (not an x86-64 host)")
        return
    # (the build's own host toolchain first, when it is there (HOOKSHOT_MINGW / the builder's tools): a clang on PATH may
    # target MSVC without its C++ library, which a64emit.cpp needs; else as test_fpx_sticky.py finds one)
    tc_flags = None
    if not os.environ.get("HOOKSHOT_MINGW") and os.name == "nt":   # (an llvm-mingw on PATH, as the tests are run here)
        w = shutil.which("clang++")
        if w and os.path.isfile(os.path.join(os.path.dirname(w), "x86_64-w64-mingw32-clang++.exe")):
            os.environ["HOOKSHOT_MINGW"] = os.path.dirname(os.path.dirname(w))
    if not a.cc and not a.cxx:
        try:
            tcc, tcxx = sticky.toolchain.find("clang", host=True), sticky.toolchain.find("clang++", host=True)
            if os.path.isfile(tcc) and os.path.isfile(tcxx):
                cc, cxx = tcc, tcxx
                tc_flags = sticky.toolchain.native_target(host=True) + sticky.toolchain.native_link(host=True)
        except Exception:
            tc_flags = None
    if tc_flags is None:
        cc = sticky.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
        cxx = sticky.compiler(a.cxx, "CXX", ("clang++", "g++", "c++"), "clang++")
    flags_of = (lambda tmp: tc_flags) if tc_flags is not None else (lambda tmp: sticky.target_flags(cc, tmp))
    if not cc or not cxx:
        print("vfminmax: skipped (no C/C++ compiler)")
        return
    t0 = time.time()
    failed, ran = [], []
    with tempfile.TemporaryDirectory(prefix="hookshot-vfminmax-") as tmp:
        generate(cxx, tmp, flags_of(tmp))
        for march in ("x86-64-v3", "x86-64-v2"):
            exe = os.path.join(tmp, "vfminmax_test_%s.exe" % march)
            sticky.build([cc] + flags_of(tmp) + ["-march=" + march] + sticky.FLAGS +
                         ["-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(sticky.KIT, "rt"), "-I" + tmp,
                          os.path.join(HERE, "vfminmax_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe], "the driver at " + march)
            r = sticky.run([exe, str(CASES), str(SEED)])
            print(r.stdout.rstrip())
            if r.returncode == 3:
                print("vfminmax: %s skipped (this CPU is not %s)" % (march, march))
                continue
            ran.append(march)
            if r.returncode:
                failed.append(march)
    if not ran:
        print("vfminmax: skipped (this CPU is not x86-64-v2)")
        return
    if failed:
        raise SystemExit("vfminmax: FAIL (%s) in %.1f s" % (", ".join(failed), time.time() - t0))
    print("vfminmax: pass in %.1f s" % (time.time() - t0))


if __name__ == "__main__":
    main()
