//! The generated sources of a standalone lift, byte for byte the Python side's: gen/a64_table.c, a64_hooks.c,
//! a64_code_slots.c (nx2/lift2/tables.py), functions.txt (nx2/lift.py), hos_image.c, a64_stubs.c, nvn2_exports.c
//! (nx2/standalone.py) and rt64/a64.h, a64_rt.c (nx2/rtgen.py: a64-kit's runtime with the 64-bit guest window).

use crate::eden::{nvn_proc_name, Facts};
use crate::image::{Hook, Image};
use std::collections::{BTreeSet, HashMap};
use std::fmt::Write;
use std::path::{Path, PathBuf};

fn fname(a: u64) -> String {
    format!("f_{a:08x}")
}

/// Python's "%#x": 0x0 for zero too
fn hx(v: u64) -> String {
    format!("{v:#x}")
}

/// a64_table.c and a64_hooks.c (tables.write): functions, every hook, the answered hooks' addresses
pub fn tables(functions: &[u64], hooks: &[Hook], answered: &BTreeSet<u64>) -> (String, String) {
    let mut fns: Vec<u64> = functions.iter().copied().chain(hooks.iter().map(|h| h.addr)).collect();
    fns.sort_unstable();
    fns.dedup();
    let mut t = String::from("#include \"a64.h\"\n");
    for &a in &fns {
        writeln!(t, "void {}(Ctx *A64_NOESC);", fname(a)).unwrap();
    }
    writeln!(t, "const uint32_t a64_fn_count = {};", fns.len()).unwrap();
    t.push_str("const uint32_t a64_fn_addr[] = {\n");
    for &a in &fns {
        writeln!(t, "0x{a:08x},").unwrap();
    }
    t.push_str("};\nconst A64Fn a64_fn_ptr[] = {\n");
    for &a in &fns {
        writeln!(t, "{},", fname(a)).unwrap();
    }
    t.push_str("};\n");
    let mut h = String::from("/* Hooked guest addresses: f_<address> is the host function (an HLE or a generated stub). */\n#include \"a64.h\"\n");
    let names: BTreeSet<&str> = hooks.iter().filter(|x| !answered.contains(&x.addr)).map(|x| x.c.as_str()).collect();
    for n in names {
        writeln!(h, "void {n}(Ctx *A64_NOESC);").unwrap();
    }
    for x in hooks {
        if answered.contains(&x.addr) {
            writeln!(h, "/* f_{:08x} answers {}: lifted IR */", x.addr, x.c).unwrap();
        } else {
            writeln!(h, "void f_{:08x}(Ctx *A64_NOESC c) {{ TAILCALL({}); }}", x.addr, x.c).unwrap();
        }
    }
    (t, h)
}

/// a64_code_slots.c (tables.write_code_slots): the relocated slots holding a function of the table
pub fn code_slots(img: &Image, facts: &Facts, functions: &[u64]) -> String {
    let mut fns: Vec<u64> = functions.iter().copied().chain(img.hooks.iter().map(|h| h.addr)).collect();
    fns.sort_unstable();
    fns.dedup();
    let bases: Vec<u64> = img.modules.iter().map(|m| m.base).collect();
    let mut slots: Vec<(u64, usize)> = facts
        .reloc_slots
        .iter()
        .filter_map(|&at| {
            let v = u64::from_le_bytes(img.read(at, 8).unwrap().try_into().unwrap());
            let k = fns.binary_search(&v).ok()?;
            (!bases.contains(&v)).then_some((at, k))
        })
        .collect();
    slots.sort_unstable();
    let mut s = String::from("/* Generated by nx2/lift.py: relocated slots holding a function of a64_table.c (lift2/tables.py) */\n#include <stdint.h>\n");
    writeln!(s, "const uint32_t a64_code_slot_count = {};", slots.len()).unwrap();
    s.push_str("const uint32_t a64_code_slot[] = {\n");
    for (a, _) in &slots {
        writeln!(s, "0x{a:08x},").unwrap();
    }
    s.push_str("};\nconst uint32_t a64_code_slot_fn[] = {\n");
    for (_, k) in &slots {
        writeln!(s, "{k},").unwrap();
    }
    s.push_str("};\n");
    s
}

/// functions.txt: every lifted function and its lifted body's size
pub fn functions_txt(sizes: &[(u64, usize)]) -> String {
    let mut s = String::new();
    for (e, n) in sizes {
        writeln!(s, "{e:08x} {n}").unwrap();
    }
    s
}

/// nvn2_exports.c (standalone.write_nvn_exports)
pub fn nvn_exports_c(names: &[String]) -> String {
    let mut s = String::from("/* Generated by nx2/lift.py --standalone: the sdk's NVN functions, routed to host/nvn2.c. */\n#include \"a64.h\"\nvoid nvn2_dispatch(Ctx *c, const char *name, void **cache);\n\n");
    for n in names {
        writeln!(s, "void imp_{n}(Ctx *A64_NOESC c) {{ static void *k[2]; nvn2_dispatch(c, \"{}\", k); }}", nvn_proc_name(n).unwrap()).unwrap();
    }
    s
}

/// llvm-cxxfilt as toolchain.find finds it: $EMSDK (else ~/emsdk)/upstream/bin, else PATH
fn cxxfilt() -> PathBuf {
    let root = std::env::var_os("EMSDK").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(std::env::var_os("HOME").unwrap_or_default()).join("emsdk"));
    let p = root.join("upstream").join("bin").join("llvm-cxxfilt");
    if p.is_file() {
        return p;
    }
    if let Some(path) = std::env::var_os("PATH") {
        for d in std::env::split_paths(&path) {
            let c = d.join("llvm-cxxfilt");
            if c.is_file() {
                return c;
            }
        }
    }
    p
}

/// symbol -> its demangled form, by one llvm-cxxfilt run (standalone.demangle: the names themselves if it fails)
fn demangle(syms: &[&str]) -> HashMap<String, String> {
    use std::io::Write as _;
    let ident = || syms.iter().map(|s| (s.to_string(), s.to_string())).collect();
    let child = std::process::Command::new(cxxfilt())
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .spawn();
    let Ok(mut child) = child else { return ident() };
    let input = syms.join("\n");
    let mut stdin = child.stdin.take().unwrap();
    let writer = std::thread::spawn(move || {
        let _ = stdin.write_all(input.as_bytes());
    });
    let out = child.wait_with_output();
    let _ = writer.join();
    let Ok(out) = out else { return ident() };
    let text = String::from_utf8_lossy(&out.stdout).into_owned();
    // (Python's str.splitlines)
    let lines: Vec<&str> = text.lines().collect();
    if lines.len() != syms.len() {
        return ident();
    }
    syms.iter().zip(lines).map(|(s, d)| (s.to_string(), d.to_string())).collect()
}

/// a64_stubs.c (standalone.gen_stubs) and the number of stubs
pub fn stubs_c(hooks: &[Hook], implemented: &BTreeSet<String>) -> (String, usize) {
    // (the C names the host defines: imp_<symbol> of each HLE / PATCH_ANSWER, and of each NVN function hooked)
    let have: std::collections::HashSet<String> = implemented
        .iter()
        .map(|s| format!("imp_{s}"))
        .chain(hooks.iter().filter(|h| nvn_proc_name(&h.sym).is_some()).map(|h| format!("imp_{}", h.sym)))
        .collect();
    let hs: Vec<&Hook> = hooks.iter().filter(|h| !have.contains(&h.c)).collect();
    let dm = demangle(&hs.iter().map(|h| h.sym.as_str()).collect::<Vec<_>>());
    let mut s = String::from("#include \"a64.h\"\n__attribute__((noreturn)) void hos_import_stop(Ctx *A64_NOESC c, const char *sym, const char *name);\n\n");
    for h in &hs {
        writeln!(s, "void {}(Ctx *A64_NOESC c) {{ hos_import_stop(c, \"{}\", \"{}\"); }}", h.c, h.sym, dm[&h.sym].replace('\\', "\\\\").replace('"', "\\\"")).unwrap();
    }
    (s, hs.len())
}

/// the SDK thread entry's start and exit hooks (standalone.thread_hooks)
fn thread_hooks(img: &Image) -> (u64, u64) {
    for m in &img.modules {
        let mut pc = m.base;
        while pc < m.base + m.size - 12 {
            if img.in_code(pc) && img.word(pc) == 0xD53BD061 && img.word(pc + 4) == 0x9107E021 && img.word(pc + 8) == 0xF9000020 {
                let mut hooks = Vec::new();
                let mut page: HashMap<u32, u64> = HashMap::new();
                let mut q = pc + 12;
                while q < pc + 12 + 4 * 40 {
                    let w = img.word(q);
                    if w & 0x9F000000 == 0x90000000 {
                        let imm = (((w >> 3) & 0x1FFFFC) | ((w >> 29) & 3)) as i64;
                        let imm = if imm & (1 << 20) != 0 { imm - (1 << 21) } else { imm };
                        page.insert(w & 31, ((q & !0xFFF) as i64 + (imm << 12)) as u64);
                    } else if w & 0xFFC00000 == 0xF9400000 && page.contains_key(&((w >> 5) & 31)) {
                        let got = page.remove(&((w >> 5) & 31)).unwrap() + ((w >> 10) & 0xFFF) as u64 * 8;
                        hooks.push(u64::from_le_bytes(img.read(got, 8).unwrap().try_into().unwrap()));
                    }
                    if hooks.len() == 2 {
                        return (hooks[0], hooks[1]);
                    }
                    q += 4;
                }
            }
            pc += 4;
        }
    }
    (0, 0)
}

/// hos_image.c (standalone.write_image_c)
pub fn image_c(img: &Image, facts: &Facts, exefs: &Path) -> Result<String, String> {
    let ex = |n: &str| facts.exports.iter().find(|e| e.0 == n).map_or(0, |e| e.1);
    let mods: Vec<_> = img.modules.iter().filter(|m| m.init != 0 && m.name != "rtld").collect();
    let p = exefs.join("main.npdm");
    let npdm = std::fs::read(&p).map_err(|e| format!("{}: {e}", p.display()))?;
    if &npdm[..4] != b"META" {
        return Err("main.npdm: no META header".into());
    }
    let le = |b: &[u8]| b.iter().rev().fold(0u64, |v, &x| v << 8 | x as u64);
    let (prio, core) = (npdm[0xE], npdm[0xF]);
    let stack = le(&npdm[0x1C..0x20]);
    let (aoff, asz) = (le(&npdm[0x70..0x74]) as usize, le(&npdm[0x74..0x78]) as usize);
    let aci = &npdm[aoff.min(npdm.len())..(aoff + asz).min(npdm.len())];
    let program_id = if aci.len() >= 4 && &aci[..4] == b"ACI0" { le(&aci[0x10..0x18]) } else { 0 };
    let main_build = img.modules.iter().find(|m| m.name == "main").map_or("", |m| m.build_id.as_str());
    let mut s = String::from("/* Generated by nx2/lift.py --standalone. */\n#include <stdint.h>\n");
    writeln!(s, "const uint64_t hos_main_stack_size = {}ULL;", hx(stack)).unwrap();
    writeln!(s, "const int hos_main_priority = {prio}, hos_main_core = {core};").unwrap();
    writeln!(s, "const uint64_t hos_image_base = {}ULL, hos_image_end = {}ULL;", hx(img.base), hx(img.end)).unwrap();
    writeln!(s, "const int hos_module_count = {};", mods.len()).unwrap();
    writeln!(s, "const uint64_t hos_module_init[] = {{{}}};", mods.iter().map(|m| format!("{}ULL", hx(m.init))).collect::<Vec<_>>().join(", ")).unwrap();
    writeln!(s, "const char *const hos_module_name[] = {{{}}};", mods.iter().map(|m| format!("\"{}\"", m.name)).collect::<Vec<_>>().join(", ")).unwrap();
    writeln!(s, "const uint64_t hos_entry_nninitStartup = {}ULL;", hx(ex("nninitStartup"))).unwrap();
    writeln!(s, "const uint64_t hos_entry_nnMain = {}ULL;", hx(ex("nnMain"))).unwrap();
    writeln!(s, "const uint64_t hos_program_id = {}ULL;   /* (main.npdm's ACI0) */", hx(program_id)).unwrap();
    writeln!(s, "const char hos_main_build_id[] = \"{main_build}\";").unwrap();
    for sym in ["_init_libc0", "_init_libc1", "_init_libc2", "nnosInitialize", "nninitInitializeSdkModule", "nvnBootstrapLoaderInternal"] {
        writeln!(s, "const uint64_t hos_entry_{} = {}ULL;", sym.trim_start_matches('_'), hx(ex(sym))).unwrap();
    }
    let (start, exit) = thread_hooks(img);
    writeln!(s, "const uint64_t hos_thread_start_hook = {}ULL, hos_thread_exit_hook = {}ULL;", hx(start), hx(exit)).unwrap();
    Ok(s)
}

const ADDR64: &str = "#ifndef A64_ADDR64\n#define A64_ADDR64 1   /* (nx2/rtgen.py: 64-bit guest window) */\n#endif\n#if A64_ADDR64\n#define A64_PTR(a) (A64_MEM + (uint64_t)(a))\n#else\n#define A64_PTR(a) (A64_MEM + (uint32_t)(a))\n#endif";
const LOOKUP: &str = "    uint32_t a = (uint32_t)addr, lo = 0, hi = a64_fn_count;";

/// rt64/a64.h and a64_rt.c (rtgen.write): a64-kit's rt/ sources with the 64-bit guest window, each substitution
/// required to match exactly once
pub fn rt64(root: &Path) -> Result<Vec<(&'static str, String)>, String> {
    let lookup_new = format!("#if A64_ADDR64\n    if (addr >> 32) return NULL;   /* (code lies below 4 GB: never a truncated match) */\n#endif\n{LOOKUP}");
    let subst: [(&str, Vec<(&str, &str)>); 2] = [
        ("a64.h", vec![("#define A64_PTR(a) (A64_MEM + (uint32_t)(a))", ADDR64)]),
        ("a64_rt.c", vec![(LOOKUP, lookup_new.as_str())]),
    ];
    let mut out = Vec::new();
    for (name, subs) in subst {
        let p = root.join("third_party/a64-kit/rt").join(name);
        let mut text = std::fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()))?;
        for (old, new) in subs {
            let n = text.matches(old).count();
            if n != 1 {
                return Err(format!("rtgen: {:?} found {n} times in a64-kit rt/{name} (expected once)", &old[..old.len().min(60)]));
            }
            text = text.replacen(old, new, 1);
        }
        out.push((name, format!("/* Generated by mkw-recomp nx2/rtgen.py from a64-kit rt/{name} (64-bit guest window). Do not edit. */\n{text}")));
    }
    Ok(out)
}
