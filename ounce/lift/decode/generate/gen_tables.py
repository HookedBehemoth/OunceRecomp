"""Generate src/tables.rs from the Python lifter's encoding tables (encoding/enc*.py).

Run from anywhere:  python3 -I -B ounce/lift/decode/generate/gen_tables.py

What it emits, per entry of enc.ENTRIES (in that order, so an entry's index is the same on both sides):
- name, template, params, mask/value and the fields (name, shift, width), read from the parsed entry;
- the validity as a truth table: the entry's `valid` expression is evaluated by Python over every combination of the
  fields it names (at most 16 bits for every entry of the tables), so the Rust validity is the Python one by
  construction, whatever helper the expression calls. An entry whose expression is "True" has no table.
- the dispatch: 4096 buckets by bits 31:20, each listing (in table order) the entries whose literal bits allow it.

The info functions the semantic templates use (enc_neon's *_info, bitmask, ...) are ported by hand in src/info.rs;
this script also writes one digest per function over its whole domain (tests/info_digests.rs) so that a unit test
proves the port equal to Python without Python. `--dump-info DIR` writes the canonical lines the digests hash.
"""
import ast
import importlib
import itertools
import os
import pkgutil
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
sys.path.insert(0, HERE)

from encoding import enc  # noqa: E402

MAX_VALID_BITS = 16
DISPATCH_SHIFT = 20          # bucket = word >> 20 (bits 31:20)


def sources():
    """(name, valid expression) of every entry, in enc.ENTRIES' order (enc._load_tables' order)"""
    out = [(e[0], e[4]) for e in enc.ENCODINGS]
    for m in sorted(pkgutil.iter_modules([os.path.dirname(enc.__file__)])):
        if m.name.startswith("enc_"):
            mod = importlib.import_module("encoding." + m.name)
            out += [(e[0], e[4]) for e in mod.ENCODINGS]
    assert [n for n, _ in out] == [e.name for e in enc.ENTRIES], "table order differs from enc.ENTRIES"
    return [v for _, v in out]


def valid_fields(entry, expr):
    """the entry's fields its validity expression reads, in field order"""
    names = {n.id for n in ast.walk(ast.parse(expr, mode="eval")) if isinstance(n, ast.Name)}
    return [f for f in entry.fields if f[0] in names]


def truth_table(entry, vf):
    bits = sum(m.bit_length() for _, _, m in vf)
    assert bits <= MAX_VALID_BITS, (entry.name, bits)
    base = {f: 0 for f, _, _ in entry.fields}
    rng = random.Random(entry.name)
    table = [0] * max(1, (1 << bits) // 64 + (1 if (1 << bits) % 64 else 0))
    for idx in range(1 << bits):
        f = dict(base)
        at = 0
        for name, _, m in reversed(vf):           # (the last field takes the low bits of the index)
            f[name] = (idx >> at) & m
            at += m.bit_length()
        ok = bool(entry.valid(**f))
        if idx % 97 == 0:                        # (the other fields do not change it)
            g = dict(f)
            for name, _, m in entry.fields:
                if name not in {x[0] for x in vf}:
                    g[name] = rng.randint(0, m)
            assert bool(entry.valid(**g)) == ok, entry.name
        if ok:
            table[idx >> 6] |= 1 << (idx & 63)
    return bits, table


def rs_param(v):
    if isinstance(v, bool):
        return "Param::Bool(%s)" % ("true" if v else "false")
    if isinstance(v, int):
        return "Param::Int(%d)" % v
    if isinstance(v, str):
        return "Param::Str(\"%s\")" % v
    raise TypeError(v)


def gen_tables():
    exprs = sources()
    out = ["// Generated by ounce/lift/decode/generate/gen_tables.py from generate/encoding/enc*.py: do not edit.",
           "#![allow(clippy::all)]", "use crate::{Encoding, Field, Param};", ""]
    for i, (e, expr) in enumerate(zip(enc.ENTRIES, exprs)):
        if expr.strip() == "True":
            continue
        vf = valid_fields(e, expr)
        bits, table = truth_table(e, vf)
        out.append("// %s: %s" % (e.name, expr))
        out.append("static VT_%d: [u64; %d] = [%s];" % (i, len(table), ", ".join("0x%x" % w for w in table)))
    out.append("")
    out.append("pub static ENCODINGS: [Encoding; %d] = [" % len(enc.ENTRIES))
    for i, (e, expr) in enumerate(zip(enc.ENTRIES, exprs)):
        fields = ", ".join('Field { name: "%s", shift: %d, width: %d }' % (n, s, m.bit_length()) for n, s, m in e.fields)
        params = ", ".join('("%s", %s)' % (k, rs_param(v)) for k, v in e.params.items())
        if expr.strip() == "True":
            vfs, vt = "&[]", "None"
        else:
            vf = valid_fields(e, expr)
            vfs = "&[%s]" % ", ".join("(%d, %d)" % (s, m.bit_length()) for _, s, m in vf)
            vt = "Some(&VT_%d)" % i
        out.append('    Encoding { id: %d, name: "%s", template: "%s", params: &[%s], mask: 0x%08x, value: 0x%08x,\n'
                   '        fields: &[%s],\n        valid_fields: %s, valid_table: %s },'
                   % (i, e.name, e.template, params, e.mask, e.value, fields, vfs, vt))
    out.append("];")
    out.append("")
    # typed field access: every field name, and per entry each field's (shift | width << 8), 0 where it has none
    names = []
    for e in enc.ENTRIES:
        for n, _, _ in e.fields:
            if n not in names:
                names.append(n)
    assert len(names) < 256
    out.append("/// A field of the encodings by name (the patterns' field names): `Insn::f(Fld::Rn)`.")
    out.append("#[allow(non_camel_case_types)]")
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    out.append("#[repr(u8)]")
    out.append("pub enum Fld { %s }" % ", ".join(names))
    out.append("pub(crate) const NFLD: usize = %d;" % len(names))
    out.append("pub(crate) static FLD_NAMES: [&str; NFLD] = [%s];" % ", ".join('"%s"' % n for n in names))
    out.append("pub(crate) static FIELD_AT: [[u16; NFLD]; %d] = [" % len(enc.ENTRIES))
    for e in enc.ENTRIES:
        at = [0] * len(names)
        for n, sh, m in e.fields:
            assert m.bit_length() > 0
            at[names.index(n)] = sh | m.bit_length() << 8
        out.append("    [%s]," % ", ".join(map(str, at)))
    out.append("];")
    out.append("")
    # dispatch
    nb = 1 << (32 - DISPATCH_SHIFT)
    hm = (0xFFFFFFFF >> DISPATCH_SHIFT) << DISPATCH_SHIFT
    starts, flat = [], []
    for b in range(nb):
        starts.append(len(flat))
        hi = b << DISPATCH_SHIFT
        for i, e in enumerate(enc.ENTRIES):
            m = e.mask & hm
            if hi & m == e.value & m:
                flat.append(i)
    starts.append(len(flat))
    assert len(flat) < 65536 and len(enc.ENTRIES) < 256
    out.append("pub(crate) const DISPATCH_SHIFT: u32 = %d;" % DISPATCH_SHIFT)
    out.append("pub(crate) static BUCKET_START: [u16; %d] = [%s];" % (len(starts), ", ".join(map(str, starts))))
    out.append("pub(crate) static BUCKET_ENTRY: [u8; %d] = [%s];" % (len(flat), ", ".join(map(str, flat))))
    sizes = [starts[k + 1] - starts[k] for k in range(nb)]
    print("buckets: %d, entries listed %d, max %d, mean %.2f" % (nb, len(flat), max(sizes), len(flat) / nb),
          file=sys.stderr)
    return "\n".join(out) + "\n"


def main():
    tables = gen_tables()
    with open(os.path.join(HERE, "..", "src", "tables.rs"), "w", newline="\n") as f:
        f.write(tables)
    if os.path.exists(os.path.join(HERE, "info_vectors.py")):
        sys.path.insert(0, HERE)
        import info_vectors
        dump = None
        if "--dump-info" in sys.argv:
            dump = sys.argv[sys.argv.index("--dump-info") + 1]
        with open(os.path.join(HERE, "..", "tests", "data", "info_digests.rs"), "w", newline="\n") as f:
            f.write(info_vectors.digests_rs(dump))


if __name__ == "__main__":
    main()
