"""The digests tests/info.rs checks src/info.rs against: each helper of generate/encoding/enc*.py evaluated by Python over its
whole domain, one line "args:result" per point, hashed (FNV-1a 64 over the lines, each ending in a newline).
Canonical text: None "None", a tuple its items joined by ",", a bool 1/0, an int in decimal, a float its f64 bits in
hex. tests/info.rs builds the same lines in the same order. gen_tables.py calls digests_rs.
"""
import itertools
import os
import struct

from encoding import enc, enc_fp, enc_neon as N


def canon(x):
    if x is None:
        return "None"
    if isinstance(x, tuple):
        return ",".join(canon(v) for v in x)
    if isinstance(x, bool):
        return str(int(x))
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        return "%016x" % struct.unpack("<Q", struct.pack("<d", x))[0]
    return x


def grid(*ranges):
    return itertools.product(*[list(r) for r in ranges])


B = range(2)


def one_shape(opcode, S, size, Q, R):
    return enc_fp.one_shape({"opcode": opcode, "S": S, "size": size, "Q": Q, "R": R})


# name -> (points, function); every point a tuple of ints (bools given as 0/1)
FUNCS = {
    "bitmask": (grid(B, range(64), range(64), (32, 64)), enc.bitmask),
    "ldst_ok": (grid(range(4), range(4)), enc.ldst_ok),
    "sysreg": (grid(B, range(8), range(16), range(16), range(8)), lambda *k: enc.SYSREGS.get(k)),
    "sys_op": (grid(range(16), range(8)), lambda *k: enc.SYS_OPS.get(k)),
    "fp_dp1_ok": (grid(range(4), range(64)), lambda *a: bool(enc_fp.fp_dp1_ok(*a))),
    "fp_int_ok": (grid(B, range(4), range(4), range(8)), lambda *a: bool(enc_fp.fp_int_ok(*a))),
    "ldst_one_ok": (grid(B, range(8), B, range(4)), lambda *a: bool(enc_fp.ldst_one_ok(*a))),
    "fp_imm_value": (grid(range(256)), lambda i: enc_fp.fp_imm_value(i, 0)),
    "fp_imm_bits": (grid(range(256), (0, 1, 3)), enc_fp.fp_imm_bits),
    "v_scale": (grid(range(4), range(4)), enc_fp.v_scale),
    "mult": (grid(range(16)), lambda o: enc_fp.MULT.get(o)),
    "arr": (grid(range(4), B), lambda s, q: enc_fp.ARR[(s, q)]),
    "one_shape": (grid(range(8), B, range(4), B, B), one_shape),
    "lowest": (grid(range(32)), N.lowest),
    "copy_info": (grid(B, B, range(32), range(16)), N.copy_info),
    "same3_info": (grid(B, B, range(4), range(32), B), lambda q, u, s, o, sc: N.same3_info(q, u, s, o, bool(sc))),
    "diff3_info": (grid(B, range(4), range(16)), N.diff3_info),
    "misc2_info": (grid(B, B, range(4), range(32), B), lambda q, u, s, o, sc: N.misc2_info(q, u, s, o, bool(sc))),
    "across_info": (grid(B, B, range(4), range(32)), N.across_info),
    "pair_info": (grid(B, range(4), range(32)), N.pair_info),
    "modimm_info": (grid(B, B, range(16), B), N.modimm_info),
    "modimm_value": (grid(B, range(16), range(256)), N.modimm_value),
    "shift_info": (grid(B, B, range(16), range(32), B), lambda q, u, h, o, sc: N.shift_info(q, u, h, o, bool(sc))),
    "shift_amount": (grid(range(5), range(4), range(16), range(8)),
                     lambda k, e, h, b: N.shift_amount("rlnwf"[k], e, h, b)),
    "elem_info": (grid(B, B, range(4), B, range(16), B),
                  lambda q, u, s, l, o, sc: N.elem_info(q, u, s, l, o, bool(sc))),
    "elem_index": (grid(range(1, 4), B, B, range(16), B), N.elem_index),
    "dot_info": (grid(B, B, range(4), range(16)), N.dot_info),
    "fp16_misc_info": (grid(B, B, range(32)), N.fp16_misc_info),
    "perm": (grid(range(8)), lambda o: N.PERM.get(o)),
}


def fnv(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def digests_rs(dump=None):
    out = ["// Generated by ounce/lift/decode/generate/gen_tables.py (info_vectors.py) from generate/encoding/enc*.py: do not edit.",
           "pub const DIGESTS: &[(&str, u64)] = &["]
    for name, (points, fn) in FUNCS.items():
        text = "".join("%s:%s\n" % (",".join(map(str, p)), canon(fn(*p))) for p in points)
        if dump:
            os.makedirs(dump, exist_ok=True)
            with open(os.path.join(dump, name + ".txt"), "w") as f:
                f.write(text)
        out.append('    ("%s", 0x%016x),' % (name, fnv(text.encode())))
    out.append("];")
    return "\n".join(out) + "\n"
